#!/bin/sh
# Writes THIRD_PARTY_NOTICES.md: the licence of every module compiled into
# the tenjin binary on any of the platforms it is released for, and of Go
# itself. Their licences ask for these notices to travel with the binaries,
# so the release archives carry the file. GoReleaser runs this before each
# build, so the file always matches the modules of that build.
set -eu

cd "$(dirname "$0")/.."
out=THIRD_PARTY_NOTICES.md

tmp=$(mktemp)
list=$(mktemp)
trap 'rm -f "$tmp" "$list"' EXIT

# Each listing on its own line of the script, not in a pipeline, so that a
# go list that fails ends the script instead of leaving modules out of the
# file: in a pipeline only the last command's failure would be seen.
for os in darwin linux windows; do
	GOOS=$os go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}{{end}}{{end}}' ./cmd/tenjin >> "$list"
done
modules=$(sort -u "$list")

notice() {
	# $1 heading, $2 folder holding the licence files
	printf '## %s\n\n' "$1"
	found=0
	for f in "$2"/LICENSE "$2"/LICENSE.txt "$2"/LICENSE.md "$2"/COPYING "$2"/NOTICE "$2"/PATENTS; do
		[ -f "$f" ] || continue
		found=1
		printf '%s\n\n```\n' "$(basename "$f")"
		# Line endings and trailing blank lines differ between modules; keep
		# the file the same wherever it is made.
		tr -d '\r' < "$f" | sed -e :a -e '/^\n*$/{$d;N;ba' -e '}'
		printf '```\n\n'
	done
	[ "$found" = 1 ] || {
		echo "no licence file for $1 in $2" >&2
		exit 1
	}
}

{
	printf '# Third-party notices\n\n'
	printf 'The tenjin binary includes the following software, under the licences below.\n'
	printf 'This file is generated by scripts/notices.sh.\n\n'
	notice "Go (the standard library and runtime)" "$(go env GOROOT)"
	for m in $modules; do
		# Assigned first: a failure inside an argument would pass unseen.
		version=$(go list -m -f '{{.Version}}' "$m")
		dir=$(go list -m -f '{{.Dir}}' "$m")
		notice "$m $version" "$dir"
	done
} > "$tmp"

# mktemp makes the file readable by its owner only; the archives carry it
# for everyone.
chmod 0644 "$tmp"
mv "$tmp" "$out"
